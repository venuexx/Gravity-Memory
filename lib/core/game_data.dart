class LevelData {
  final int id;
  final List<List<int>> grid; // 0=wall, 1=path, 2=start, 3=exit
  final int memorizeSeconds;
  final int cols;
  final int rows;

  const LevelData({
    required this.id,
    required this.grid,
    required this.memorizeSeconds,
    required this.cols,
    required this.rows,
  });

  // Player start position
  (int row, int col) get startPos {
    for (int r = 0; r < rows; r++) {
      for (int c = 0; c < cols; c++) {
        if (grid[r][c] == 2) return (r, c);
      }
    }
    return (0, 0);
  }

  // Exit position
  (int row, int col) get exitPos {
    for (int r = 0; r < rows; r++) {
      for (int c = 0; c < cols; c++) {
        if (grid[r][c] == 3) return (r, c);
      }
    }
    return (rows - 1, cols - 1);
  }
}

class LevelResult {
  final int levelId;
  final int stars; // 1-3
  final int timeSeconds;
  final int moves;

  const LevelResult({
    required this.levelId,
    required this.stars,
    required this.timeSeconds,
    required this.moves,
  });

  int get score {
    final timeBonus = (300 - timeSeconds).clamp(0, 300);
    final moveBonus = (200 - moves).clamp(0, 200);
    return stars * 500 + timeBonus + moveBonus;
  }
}

